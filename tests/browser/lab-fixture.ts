/* Synthetic Lab history for browser tests and local previews ONLY. Answers are
 * generated by a seeded fixture, passed through the real engine transitions. */
export const TODAY = '2026-10-18';
const days = (count: number) => Array.from({ length: count }, (_, i) => new Date(Date.parse(TODAY + 'T12:00:00Z') - (count - 1 - i) * 86_400_000).toISOString().slice(0, 10));
function complete(run: LabRun, answer: (unit: LabRun['units'][number], i: number) => unknown, keepPending = 0): LabRun {
  let next = run, t = run.createdAt;
  run.units.forEach((u, i) => { if (i >= run.units.length - keepPending) return; t += 60_000;
    next = applyLabResult(next, u.id, `${run.id}/${u.id}#1`, t, 'sha256:fixture', successful(answer(u, i)), t + 900); });
  return next;
}
export function labHistory(count = 21, options: { pendingToday?: boolean } = {}): Record<LabExperiment, LabRun[]> {
  const out: Record<LabExperiment, LabRun[]> = { verdict: [], coin: [], companions: [], mystery: [] };
  for (const date of days(count)) {
    const random = rng(Date.parse(date) / 86_400_000), now = Date.parse(date + 'T09:30:00Z'), pending = options.pendingToday && date === TODAY ? 3 : 0;
    let coin = complete(newCoinRun(date, 'gemini-3.5-flash-lite', now), u => ({ result: random() < (u.condition === 'neutral' ? 0.68 : 0.55) ? 'heads' : 'tails' }), pending);
    if (date === days(count)[2]) coin = closeRun(applyLabResult(newCoinRun(date, 'gemini-3.5-flash-lite', now), 'neutral-1', 'x#1', now, 'sha256:fixture', successful({ result: 'edge' }), now + 1), 'window_closed', now + 2);
    out.coin.push(coin);
    const favourite: Record<CharacterId, CharacterId[]> = { A: ['F', 'E'], B: ['C', 'A'], C: ['E', 'D'], D: ['F', 'C'], E: ['C', 'A'], F: ['A', 'D'] };
    out.companions.push(complete(newCompanionRun(date, 'gemini-3.5-flash-lite', now), u => {
      const others = CHARACTER_IDS.filter(o => o !== u.resident), first = random() < 0.7 ? favourite[u.resident][0]! : others[Math.floor(random() * 5)]!;
      const second = random() < 0.5 ? favourite[u.resident].find(x => x !== first) ?? others.find(x => x !== first)! : shuffle(others.filter(x => x !== first), random)[0]!;
      return { choices: [first, second], reason: 'A calm walk with someone who listens.' };
    }, pending));
    const mystery = newMysteryRun(date, 'gemini-3.5-flash-lite', now), culprit = (mystery.input as { culprit: CharacterId }).culprit;
    out.mystery.push(complete(mystery, u => { const right = random() < (u.resident === culprit ? 0.5 : 0.72);
      return { culprit: right ? culprit : CHARACTER_IDS.filter(x => x !== culprit)[Math.floor(random() * 5)], explanation: right ? 'Only that statement can be the false one while the other five hold.' : 'Two statements seemed to clash, so I picked the speaker in the middle.', confidence: 40 + Math.floor(random() * 60) }; }, pending));
    const debate = completedConversation(date);
    if (date !== days(count)[5]) out.verdict.push(complete(newVerdictRun({ id: debate.id, protocol: debate.protocol, case: debate.case!, posts: debate.posts }, 'gemini-3.5-flash-lite', now),
      u => ({ ranking: shuffle(CHARACTER_IDS.filter(x => x !== u.resident), random), reason: 'Their reasoning stayed closest to what the case actually says.' }), pending));
  }
  return out;
}
const schedule = { enabled: true, model: 'gemini-3.5-flash-lite', hourUtc: 9, activatedOn: days(21)[0]!, today: TODAY };
const strip = (run: LabRun) => ({ ...run, units: run.units.map(u => ({ ...u, receipts: [] })) });
/** Serves the Lab and debate APIs from fixtures. Counts every request so tests can prove pages only read. */
export async function labRoutes(page: Page, options: { pendingToday?: boolean; empty?: boolean } = {}) {
  const history = options.empty ? { verdict: [], coin: [], companions: [], mystery: [] } as Record<LabExperiment, LabRun[]> : labHistory(21, options);
  const methods: string[] = [];
  const day = (experiment: LabExperiment, date: string) => {
    const run = history[experiment].find(r => r.date === date) ?? null;
    if (run) return { date, run, availability: run.status === 'running' ? 'pending' : run.status === 'unavailable' ? 'unavailable' : 'recorded', reason: run.reason };
    if (options.empty) return { date, run: null, availability: date === TODAY ? 'pending' : 'not_recorded', reason: date === TODAY ? 'scheduled' : null };
    return { date, run: null, availability: experiment === 'verdict' && date >= schedule.activatedOn ? 'unavailable' : 'not_recorded', reason: experiment === 'verdict' && date >= schedule.activatedOn ? 'debate_incomplete' : null };
  };
  await page.route('**/__habitat/v1/lab**', route => {
    methods.push(route.request().method());
    const path = new URL(route.request().url()).pathname.replace('/__habitat/v1/lab', '');
    if (!path) return route.fulfill({ json: { schedule: options.empty ? { ...schedule, activatedOn: TODAY } : schedule,
      today: Object.fromEntries((['verdict', 'coin', 'companions', 'mystery'] as const).map(e => [e, day(e, TODAY)])),
      latest: Object.fromEntries((['verdict', 'coin', 'companions', 'mystery'] as const).map(e => [e, history[e].at(-1)?.date ?? null])) } });
    const [, experiment, date] = path.split('/') as [string, LabExperiment, string | undefined];
    if (!(experiment in history)) return route.fulfill({ status: 400, json: { error: 'invalid_lab_request' } });
    return route.fulfill({ json: date ? day(experiment, date) : { experiment, runs: [...history[experiment]].reverse().map(strip), schedule } });
  });
  const conversation = publicDay(completedConversation(TODAY), 0);
  const older = publicDay(completedConversation('2026-09-20'), 0);
  await page.route('**/__habitat/v1/debates**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/recommendation')) return route.fulfill({ json: { recommended: false, recommendations: 0 } });
    if (path.endsWith('/' + TODAY)) return route.fulfill({ json: conversation });
    if (path.endsWith('/2026-09-20')) return route.fulfill({ json: older });
    return route.fulfill({ json: { entries: [conversation, older].map(({ posts, ...card }) => ({ ...card, postCount: posts.length })), nextCursor: null, schedule: { hourUtc: 9, enabled: true, model: conversation.model } } });
  });
  return { methods, history };
}
